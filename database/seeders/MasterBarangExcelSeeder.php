            // A. Batch Upsert Master Barang
            $barangUpsertData = [];
            foreach ($dataExcel as $row) {
                $satuanTerkecilKey = strtolower(trim($row['satuan_terkecil']));
                $baseUnitId = $masterSatuan[$satuanTerkecilKey] ?? null;
                $isStock = isset($row['is_stock']) ? ($row['is_stock'] ? 1 : 0) : 1;

                $barangUpsertData[] = [
                    'kode_barang'  => $row['kode_barang'],
                    'nama_barang'  => $row['nama_barang'],
                    'base_unit_id' => $baseUnitId,
                    'is_stock'     => $isStock,
                    'created_at'   => $now,
                    'updated_at'   => $now,
                ];
            }

            MasterBarang::upsert(
                $barangUpsertData,
                ['kode_barang'],
                ['nama_barang', 'base_unit_id', 'is_stock', 'updated_at']
            );

            // Ambil mapping [kode_barang => id] yang baru saja di-upsert
            $kodeBarangList = array_column($dataExcel, 'kode_barang');
            $barangMap = MasterBarang::whereIn('kode_barang', $kodeBarangList)
                ->pluck('id', 'kode_barang')
                ->toArray();

            // B. Batch Upsert Satuan Konversi
            $konversiUpsertData = [];
            foreach ($dataExcel as $row) {
                $barangId = $barangMap[$row['kode_barang']] ?? null;
                if (!$barangId) continue;

                $konversiList = $row['konversi'] ?? [
                    [
                        'satuan'          => $row['satuan'],
                        'jumlah_konversi' => $row['jumlah_konversi'] ?? 1,
                        'is_default'      => strtolower(trim($row['satuan_nota_masuk_default'] ?? $row['satuan'])) === strtolower(trim($row['satuan'])),
                    ]
                ];

                foreach ($konversiList as $k) {
                    $satuanKey = strtolower(trim($k['satuan']));
                    $satuanId = $masterSatuan[$satuanKey] ?? $masterSatuan[strtolower(trim($row['satuan_terkecil']))];

                    $konversiUpsertData[] = [
                        'barang_id'        => $barangId,
                        'satuan_id'        => $satuanId,
                        'konversi_ke_base' => $k['jumlah_konversi'],
                        'is_default'       => !empty($k['is_default']) ? 1 : 0,
                        'created_at'       => $now,
                        'updated_at'       => $now,
                    ];
                }
            }

            if (!empty($konversiUpsertData)) {
                BarangSatuanKonversi::upsert(
                    $konversiUpsertData,
                    ['barang_id', 'satuan_id'],
                    ['konversi_ke_base', 'is_default', 'updated_at']
                );
            }

            // C. Batch Upsert Stock Gudang UBS (Hanya untuk barang dengan is_stock = true)
            if (!empty($allUbsIds)) {
                // Filter kode barang yang is_stock = true
                $stockableKodeList = [];
                foreach ($dataExcel as $row) {
                    $isStock = $row['is_stock'] ?? true;
                    if ($isStock) {
                        $stockableKodeList[] = $row['kode_barang'];
                    }
                }

                $stockGudangUpsertData = [];
                foreach ($barangMap as $kode => $barangId) {
                    if (!in_array($kode, $stockableKodeList)) {
                        continue;
                    }

                    foreach ($allUbsIds as $ubsId) {
                        $stockGudangUpsertData[] = [
                            'barang_id'     => $barangId,
                            'stock_type'    => 'UBS',
                            'ubs_id'        => $ubsId,
                            'jumlah_stock'  => 0,
                            'minimal_stock' => 0,
                            'created_at'    => $now,
                            'updated_at'    => $now,
                        ];
                    }
                }

                // Chunk per 500 rows agar query sangat cepat dan tidak melebihi parameter limit
                foreach (array_chunk($stockGudangUpsertData, 500) as $chunk) {
                    StockGudang::upsert(
                        $chunk,
                        ['barang_id', 'stock_type', 'ubs_id'],
                        ['updated_at']
                    );
                }
            }
        });

        $this->command->info('Seeder Master Barang & Satuan Konversi (246 item) berhasil dijalankan secara instan!');
    }
