        $uniqueSatuanNames = [];
        foreach ($dataExcel as $row) {
            $uniqueSatuanNames[strtolower(trim($row['satuan_terkecil']))] = trim($row['satuan_terkecil']);
            if (isset($row['konversi'])) {
                foreach ($row['konversi'] as $k) {
                    $uniqueSatuanNames[strtolower(trim($k['satuan']))] = trim($k['satuan']);
                }
            } else {
                $uniqueSatuanNames[strtolower(trim($row['satuan']))] = trim($row['satuan']);
            }
        }

        // Cache Master Satuan yang sudah ada
        $existingSatuan = MasterSatuan::all();
        $masterSatuan = $existingSatuan->mapWithKeys(function ($item) {
            return [strtolower(trim($item->nama)) => $item->id];
        })->toArray();

        // Buat satuan baru yang belum ada
        foreach ($uniqueSatuanNames as $key => $rawName) {
            if (!isset($masterSatuan[$key])) {
                $created = MasterSatuan::create(['nama' => $rawName]);
                $masterSatuan[$key] = $created->id;
            }
        }

